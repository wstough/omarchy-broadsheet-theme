#!/bin/bash
# Writes shell.toml for OmaPaper and/or OmaPaper Dark: Omarchy's generated bar/popup/lock styling
# (so every color still comes from colors.toml) with 1px borders on every surface, matching the
# 1px window borders. Omarchy's default is 2px, which looks heavier than the windows.
# Usage: tools/make-shell-toml.sh [omapaper] [omapaper-dark]   (defaults to both; re-applies the current theme)
set -e
THEMES=~/.config/omarchy/themes
current=$(cat ~/.local/state/omarchy/current/theme.name)
for t in "${@:-omapaper omapaper-dark}"; do for t in $t; do
  rm -f "$THEMES/$t/shell.toml"
  omarchy theme set "$t" >/dev/null 2>&1          # let Omarchy generate shell.toml from colors.toml
  python3 - ~/.local/state/omarchy/current/theme/shell.toml "$THEMES/$t/shell.toml" <<'PY'
import re, sys
src, out = sys.argv[1:]
s = open(src).read()
s = "# OmaPaper: generated by tools/make-shell-toml.sh — Omarchy's styling with 1px borders.\n" + s
def add(section, line):
    global s
    s = re.sub(rf"(^\[{section}\]\n)", rf"\1{line}\n", s, count=1, flags=re.M)
add("hyprland", "active-border-width = 1")
for sec in ["popups", "tooltip", "notifications", "launcher", "menu", "polkit", "lock"]:
    add(sec, "border-width = 1")
open(out, "w").write(s)
PY
  echo "wrote $THEMES/$t/shell.toml"
done; done
omarchy theme set "$current" >/dev/null 2>&1
